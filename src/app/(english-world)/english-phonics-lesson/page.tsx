function WordBuilderMobile({ letterData, onComplete, onWrong }: {
  letterData: EnglishLetter;
  onComplete: (clientX: number, clientY: number) => void;
  onWrong: () => void;
}) {
  const word = letterData.word;
  const [shuffledLetters, setShuffledLetters] = useState<Array<{ id: number; letter: string }>>([]);
  const [placedLetters, setPlacedLetters] = useState<Array<{ id: number; letter: string }>>([]);
  const [wrongShakeId, setWrongShakeId] = useState<number | null>(null);
  const [isComplete, setIsComplete] = useState(false);

  useEffect(() => {
    const letters = word.split('').map((letter, i) => ({ id: i, letter }));
    let shuffled = [...letters];
    let attempts = 0;
    while (shuffled.map(l => l.letter).join('') === word && attempts < 10) {
      shuffled = [...letters].sort(() => Math.random() - 0.5);
      attempts++;
    }
    setShuffledLetters(shuffled);
    setPlacedLetters([]);
    setWrongShakeId(null);
    setIsComplete(false);
  }, [word]);

  const handleLetterClick = (item: { id: number; letter: string }, e: React.MouseEvent<HTMLButtonElement>) => {
    if (isComplete) return;
    const nextExpectedLetter = word[placedLetters.length];
    
    if (item.letter.toLowerCase() === nextExpectedLetter.toLowerCase()) {
      setPlacedLetters(prev => [...prev, item]);
      setShuffledLetters(prev => prev.filter(l => l.id !== item.id));
      playCoinSound();
      
      if (placedLetters.length + 1 === word.length) {
        setIsComplete(true);
        speakWord(word);
        const cx = e.clientX;
        const cy = e.clientY;
        setTimeout(() => { onComplete(cx, cy); }, 600);
      }
    } else {
      setWrongShakeId(item.id);
      playBuzzSound();
      onWrong();
      setTimeout(() => setWrongShakeId(null), 500);
    }
  };

  return (
    <GlassCard className="w-full max-w-md mx-auto p-3" accentColor={letterData.color} isMobile={true} useBgImage={true}>
      <div className="flex flex-col items-center gap-2">
        <motion.div initial={{ opacity: 0, y: -10 }} animate={{ opacity: 1, y: 0 }} className="px-3 py-1.5 rounded-2xl"
          style={{ background: 'linear-gradient(135deg, rgba(255,255,255,0.95), rgba(245,245,255,0.9))', border: `2px solid ${letterData.color}66`, boxShadow: `0 4px 15px ${letterData.color}44` }}>
          <span className="font-black text-xs text-gray-800">Arrange letters to spell the word</span>
        </motion.div>
        <motion.div animate={{ y: [0, -3, 0] }} transition={{ duration: 3, repeat: Infinity, ease: 'easeInOut' }}
          className="rounded-2xl flex items-center justify-center border-2 flex-shrink-0 relative overflow-hidden"
          style={{ width: 70, height: 70, background: `linear-gradient(145deg, ${letterData.gradient[0]}44, ${letterData.gradient[1]}33)`, borderColor: `${letterData.color}77`, boxShadow: `0 6px 18px ${letterData.color}66` }}>
          <EmojiOrIcon word={letterData.word} emoji={letterData.emoji} size={56} color={letterData.color} />
        </motion.div>
        <div className="text-center">
          <div className="font-bold text-xs" style={{ color: letterData.color }}>{letterData.wordAr}</div>
        </div>
        <CircularSoundButton onClick={() => speakWord(word)} color={letterData.color} size={38} />
        <div className="flex items-center justify-center gap-1.5 flex-wrap mt-1 min-h-[48px]" dir="ltr">
          {word.split('').map((letter, idx) => {
            const placedItem = placedLetters[idx];
            const isFilled = !!placedItem;
            return (
              <div key={`slot-${idx}`}
                className="rounded-lg flex items-center justify-center flex-shrink-0 border-2 relative overflow-hidden transition-all duration-200"
                style={{ width: 38, height: 44, background: isFilled ? `linear-gradient(145deg, ${letterData.gradient[0]}, ${letterData.gradient[1]})` : 'rgba(255,255,255,0.05)', borderColor: isFilled ? letterData.color : `${letterData.color}55`, borderStyle: isFilled ? 'solid' : 'dashed', boxShadow: isFilled ? `0 4px 12px ${letterData.color}aa` : 'none' }}>
                {!isFilled && (
                  <span className="font-black absolute inset-0 flex items-center justify-center pointer-events-none"
                    style={{ fontSize: '1.4rem', lineHeight: 1, color: letterData.color, opacity: 0.25 }}>{letter}</span>
                )}
                {isFilled && (
                  <motion.span key={`placed-${placedItem.id}`}
                    initial={{ scale: 0.5, opacity: 0 }} animate={{ scale: 1, opacity: 1 }}
                    transition={{ duration: 0.2 }}
                    className="font-black text-white relative z-10"
                    style={{ fontSize: '1.5rem', lineHeight: 1 }}>
                    {placedItem.letter}
                  </motion.span>
                )}
              </div>
            );
          })}
        </div>
        <div className="flex items-center justify-center gap-2 flex-wrap mt-1 min-h-[46px]" dir="ltr">
          {shuffledLetters.map((item) => {
            const isShaking = wrongShakeId === item.id;
            return (
              <motion.button key={`shuffled-${item.id}`}
                animate={isShaking ? { x: [-6, 6, -6, 6, 0] } : { scale: 1, opacity: 1 }}
                transition={isShaking ? { duration: 0.4 } : { duration: 0.15 }}
                whileTap={{ scale: 0.9 }}
                onClick={(e) => handleLetterClick(item, e)}
                disabled={isComplete}
                className="rounded-lg flex items-center justify-center flex-shrink-0 border-2 active:scale-90 transition-transform"
                style={{ width: 42, height: 42, background: isShaking ? 'linear-gradient(145deg, #FF4444, #CC0000)' : 'linear-gradient(145deg, rgba(255,255,255,0.98), rgba(245,245,255,0.95))', borderColor: isShaking ? '#FF4444' : `${letterData.color}aa`, boxShadow: isShaking ? '0 4px 15px rgba(255,68,68,0.6)' : `0 4px 14px ${letterData.color}55`, touchAction: 'manipulation', WebkitTapHighlightColor: 'transparent' }}>
                <span className="font-black pointer-events-none text-slate-900" style={{ fontSize: '1.5rem', lineHeight: 1 }}>
                  {item.letter}
                </span>
              </motion.button>
            );
          })}
        </div>
      </div>
    </GlassCard>
  );
}

function SpeakingPractice({ letterData, isMobile, onSuccess, onSkip }: {
  letterData: EnglishLetter; isMobile: boolean;
  onSuccess: (clientX: number, clientY: number) => void; onSkip: () => void;
}) {
  const [isListening, setIsListening] = useState(false);
  const [transcript, setTranscript] = useState('');
  const [status, setStatus] = useState<'idle' | 'listening' | 'success' | 'try-again' | 'error'>('idle');
  const [attempts, setAttempts] = useState(0);
  const [supported, setSupported] = useState(true);

  const recognitionRef = useRef<any>(null);
  const micButtonRef = useRef<HTMLButtonElement>(null);
  const safetyTimeoutRef = useRef<NodeJS.Timeout | null>(null);

  const target = letterData.word;
  const targetAr = letterData.wordAr;

  useEffect(() => {
    if (typeof window === 'undefined') return;
    const SpeechRecognition =
      (window as any).SpeechRecognition || (window as any).webkitSpeechRecognition;
    if (!SpeechRecognition) { setSupported(false); return; }

    const recognition = new SpeechRecognition();
    recognition.lang = 'en-US';
    recognition.continuous = false;
    recognition.interimResults = false;
    recognitionRef.current = recognition;

    return () => {
      if (safetyTimeoutRef.current) clearTimeout(safetyTimeoutRef.current);
    };
  }, []);

  const handleStart = () => {
    if (!recognitionRef.current || isListening) return;

    setTranscript(''); setStatus('listening'); setIsListening(true);

    safetyTimeoutRef.current = setTimeout(() => {
      if (isListening) {
        recognitionRef.current.stop();
        setStatus('try-again');
        setIsListening(false);
      }
    }, 6000);

    recognitionRef.current.onresult = (event: any) => {
      const resultText = event.results[0][0].transcript.toLowerCase().trim();
      setTranscript(resultText);
      setIsListening(false);

      if (resultText.includes(target.toLowerCase()) || target.toLowerCase().includes(resultText) || resultText[0] === target.toLowerCase()[0]) {
        setStatus('success');
        let cx = window.innerWidth / 2, cy = window.innerHeight / 2;
        if (micButtonRef.current) {
          const rect = micButtonRef.current.getBoundingClientRect();
          cx = rect.left + rect.width / 2; cy = rect.top + rect.height / 2;
        }
        setTimeout(() => onSuccess(cx, cy), 1200);
      } else {
        setStatus('try-again');
        setAttempts(a => a + 1);
      }
    };

    recognitionRef.current.onerror = () => {
      setIsListening(false);
      setStatus('try-again');
      setAttempts(a => a + 1);
    };

    recognitionRef.current.onend = () => {
      setIsListening(false);
    };

    try {
      recognitionRef.current.start();
    } catch {
      setIsListening(false);
      setStatus('error');
    }
  };

  if (!supported) {
    return (
      <motion.div initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} className="w-full max-w-md mx-auto">
        <GlassCard className="p-6 text-center" accentColor={letterData.color} isMobile={isMobile}>
          <div className="text-5xl mb-3">😅</div>
          <h3 className="text-lg font-black text-white mb-2">Speech is not supported</h3>
          <p className="text-white/60 text-sm mb-4">Please try using Google Chrome or Microsoft Edge</p>
          <button onClick={onSkip} className="px-8 py-3 rounded-2xl font-black text-white"
            style={{ background: `linear-gradient(135deg, ${letterData.gradient[0]}, ${letterData.gradient[1]})` }}>
            Skip Lesson ⏭️
          </button>
        </GlassCard>
      </motion.div>
    );
  }

  return (
    <motion.div key={`speak-word-${target}`}
      initial={{ opacity: 0, x: 60 }} animate={{ opacity: 1, x: 0 }} exit={{ opacity: 0, x: -60 }}
      className="w-full flex items-center justify-center">

      <GlassCard className={`mx-auto ${isMobile ? 'w-full max-w-[340px] p-3' : 'w-full max-w-md p-5'}`}
        accentColor={letterData.color} isMobile={isMobile} useBgImage={isMobile}>
        <div className={`flex flex-col items-center ${isMobile ? 'gap-2' : 'gap-3'}`}>
          <div className="flex items-center gap-2">
            <div className={isMobile ? 'text-2xl' : 'text-3xl'}>🎤</div>
            <div className="text-center">
              <h3 className={`font-black text-white leading-tight ${isMobile ? 'text-sm' : 'text-lg'}`}>انطق الكلمة</h3>
              <p className={`text-white/60 font-bold ${isMobile ? 'text-[9px]' : 'text-xs'}`}>Speak clearly into your mic</p>
            </div>
          </div>

          <div className={`w-full rounded-xl border-2 text-center backdrop-blur-md ${isMobile ? 'p-2' : 'p-3'}`}
            style={{ background: `linear-gradient(135deg, ${letterData.color}22, ${letterData.color}08)`, borderColor: `${letterData.color}55` }}>
            <div className="flex items-center justify-center gap-2 mb-0.5">
              <span className={isMobile ? 'text-xl' : 'text-2xl'}>{letterData.emoji}</span>
              <p className={`font-black text-white ${isMobile ? 'text-lg' : 'text-2xl'}`} dir="ltr">{target}</p>
            </div>
            <p className={`font-bold ${isMobile ? 'text-[10px]' : 'text-xs'}`} style={{ color: letterData.color }}>{targetAr}</p>
          </div>

          <motion.button ref={micButtonRef}
            whileHover={!isListening ? { scale: 1.05 } : {}}
            whileTap={{ scale: 0.95 }}
            onClick={handleStart}
            className={`rounded-full flex items-center justify-center ${isMobile ? 'w-14 h-14' : 'w-16 h-16'}`}
            style={{
              background: isListening ? 'linear-gradient(135deg, #FF4444, #C70039)' : `linear-gradient(135deg, ${letterData.gradient[0]}, ${letterData.gradient[1]})`,
              boxShadow: isListening ? '0 0 20px rgba(255,68,68,0.6)' : `0 8px 25px ${letterData.color}66`
            }}>
            <Mic className="text-white" size={24} />
          </motion.button>

          {isListening && <p className="text-red-400 font-bold text-xs animate-pulse">Listening... بسمعك</p>}
          {status === 'success' && <p className="text-green-400 font-bold text-xs">Excellent! ممتاز 🎉</p>}
          {status === 'try-again' && <p className="text-yellow-400 font-bold text-xs">Try again, speak louder!</p>}

          {(attempts >= 1 || status === 'try-again') && (
            <button onClick={onSkip} className="mt-2 text-white/60 hover:text-white underline text-xs font-bold transition-all">
              تخطي هذا الحرف ⏭️
            </button>
          )}
        </div>
      </GlassCard>
    </motion.div>
  );
}

