export function hitTest(x: number, y: number, shapes: Polygon[]): boolean {
  for (const poly of shapes) {
    if (isPointInPolygon(x, y, poly)) return true;
  }
  return false;
}

export function isPointInPolygon(x: number, y: number, polygon: Polygon): boolean {
  let inside = false;
  for (let i = 0, j = polygon.length - 2; i < polygon.length; i += 2) {
    const xi = polygon[i], yi = polygon[i + 1];
    const xj = polygon[j], yj = polygon[j + 1];
    const intersect = ((yi > y) !== (yj > y)) && (x < (xj - xi) * (y - yi) / (yj - yi) + xi);
    if (intersect) inside = !inside;
    j = i;
  }
  return inside;
}

export function polygonToSvgPoints(poly: Polygon): string {
  const pts = [];
  for (let i = 0; i < poly.length; i += 2) {
    pts.push(`${poly[i]},${poly[i + 1]}`);
  }
  return pts.join(' ');
}

export function getPolygonBounds(poly: Polygon) {
  let minX = 100, maxX = 0, minY = 100, maxY = 0;
  for (let i = 0; i < poly.length; i += 2) {
    const x = poly[i]; const y = poly[i + 1];
    if (x < minX) minX = x; if (x > maxX) maxX = x;
    if (y < minY) minY = y; if (y > maxY) maxY = y;
  }
  return { x: minX, y: minY, w: maxX - minX, h: maxY - minY };
}

